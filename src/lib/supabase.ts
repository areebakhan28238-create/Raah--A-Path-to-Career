/**
 * Test connectivity with Supabase project
 */
export async function testSupabaseConnection(): Promise<{ connected: boolean; error?: string; latencyMs: number }> {
  const start = performance.now();
  try {
    const { error } = await supabase.auth.getSession();
    const latencyMs = Math.round(performance.now() - start);
    if (error) {
      return { connected: false, error: error.message, latencyMs };
    }
    return { connected: true, latencyMs };
  } catch (err: any) {
    return { connected: false, error: err?.message || 'Connection failed', latencyMs: Math.round(performance.now() - start) };
  }
}

/**
 * Check if the custom tables exist in public schema
 */
export async function verifySupabaseTables(): Promise<{ exists: boolean; missingTables: string[] }> {
  const tables = ['students', 'video_progress', 'quiz_scores', 'coding_submissions', 'project_progress'];
  const missing: string[] = [];

  for (const table of tables) {
    try {
      const { error } = await supabase.from(table).select('count', { count: 'exact', head: true });
      if (error && (error.code === '42P01' || error.message.includes('Could not find the table'))) {
        missing.push(table);
      }
    } catch {
      missing.push(table);
    }
  }

  return {
    exists: missing.length === 0,
    missingTables: missing,
  };
}

/**
 * Sync complete User Profile & Learning state to Supabase
 */
export async function syncUserProfileToSupabase(user: UserProfile): Promise<boolean> {
  if (!user.email) return false;

  try {
    // 1. Try to update auth metadata if signed in
    try {
      await supabase.auth.updateUser({
        data: {
          fullName: user.fullName,
          college: user.college,
          currentYear: user.currentYear,
          targetCareer: user.targetCareer,
          xp: user.xp,
          careerReadinessScore: user.careerReadinessScore,
          learningStreak: user.learningStreak,
          completedCoursesCount: user.completedCourses.length,
          solvedProblemsCount: user.solvedProblems.length,
          lastActive: new Date().toISOString(),
        },
      });
    } catch {
      // Ignored if user not in active Supabase auth session
    }

    // 2. Upsert to public.students table
    const { error } = await supabase.from('students').upsert(
      {
        id: user.id || `usr_${user.email.replace(/[^a-zA-Z0-9]/g, '_')}`,
        email: user.email.toLowerCase().trim(),
        full_name: user.fullName,
        college: user.college,
        branch: user.branch,
        current_year: user.currentYear,
        current_semester: user.currentSemester,
        target_career: user.targetCareer,
        xp: user.xp,
        career_readiness_score: user.careerReadinessScore,
        streak: user.learningStreak,
        raw_profile_data: user,
        updated_at: new Date().toISOString(),
      },
      { onConflict: 'email' }
    );

    if (error) {
      console.warn('Note: students table sync waiting for schema:', error.message);
      return false;
    }
    return true;
  } catch (e: any) {
    console.warn('Supabase profile sync note:', e.message);
    return false;
  }
}

